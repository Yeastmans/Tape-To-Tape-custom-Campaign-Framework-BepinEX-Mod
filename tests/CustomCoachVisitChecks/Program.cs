using CampaignCore;
using EndlessMode;
using Rogue.NPC.CoachNPC;
using STS.Map;
using Tape2Tape;
int checks=0;
void Check(bool pass,string text) { if(!pass)throw new Exception(text); checks++; }
var first=new CustomCoachDefinition { Name="A", Relics={"a"} };
var second=new CustomCoachDefinition { Name="B", Relics={"b"} };
var layout=new MapLayout { Nodes=[new(){Id="a",Type="Coach",CustomCoach=first},new(){Id="b",Type="Coach",CustomCoach=second},new(){Id="normal",Type="Coach"}] };
var map=new MapObject(); map.mapManager.CurrentMap=new Map { Layout=layout };
var a=new CoachMapNode { Parent=map,Node=new(){NodeIndex=0} };
var b=new CoachMapNode { Parent=map,Node=new(){NodeIndex=1} };
var normal=new CoachMapNode { Parent=map,Node=new(){NodeIndex=2} };
var shared=new CoachEvent(); EventNode eventA=shared,eventB=shared,ordinary=shared;
CustomCoachRuntime.Bind(a,ref eventA); CustomCoachRuntime.Bind(b,ref eventB); CustomCoachRuntime.Bind(normal,ref ordinary);
Check(eventA.Pointer!=shared.Pointer && eventB.Pointer!=eventA.Pointer && ordinary==shared,"Custom visits own separate events while ordinary Coach retains original");
first.Relics.Clear(); first.Relics.Add("edited-after-launch");
Check(CustomCoachRuntime.Begin((CoachEvent)eventA,out var scope),"Bound Coach can initialize");
Check(CustomCoachScope.Current.Relics.SetEquals(["a"]),"Deferred initialization uses launch snapshot");
CustomCoachRuntime.Begin((CoachEvent)eventB,out var nested); Check(CustomCoachScope.Current.Relics.SetEquals(["b"]),"Second event selects its own pool"); nested.Dispose();
Check(CustomCoachScope.Current.Relics.SetEquals(["a"]),"Nested call restores original node pool");
CustomCoachRuntime.Begin(shared,out var native); Check(CustomCoachScope.Current==null,"Ordinary initialization cannot inherit another event's pool"); native.Dispose(); scope.Dispose();
Check(CustomCoachScope.Current==null,"Completion leaves no global override");
CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); CustomCoachRuntime.Finish((CoachEvent)eventA); scope.Dispose();
Check(CustomCoachRuntime.Empty(eventA) && eventA.canSkip && !shared.canSkip,"Exhaustion enables only the bound event's leave action");
eventA.eventChoices.Add(new EventChoice()); CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); CustomCoachRuntime.Finish((CoachEvent)eventA); scope.Dispose();
Check(!CustomCoachRuntime.Empty(eventA) && !eventA.canSkip,"Reroll restores native skip policy when choices return");
CustomRewardRuntime.Reject=true;
Check(!CustomCoachRuntime.Begin((CoachEvent)eventA,out scope) && CustomCoachRuntime.Empty(eventA) && eventA.canSkip,"Definition conflicts fail closed with a leave action"); scope.Dispose(); CustomRewardRuntime.Reject=false;
var previousRun=CampaignUtil.CampaignState.runData; CampaignUtil.CampaignState.runData=new Run();
CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); Check(CustomCoachScope.Current==null,"New run rejects previous visit"); scope.Dispose(); CampaignUtil.CampaignState.runData=previousRun;
var graph=map.mapManager.CurrentMap; map.mapManager.CurrentMap=new Map { Layout=layout };
CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); Check(CustomCoachScope.Current==null,"Changed map graph rejects deferred previous visit"); scope.Dispose(); map.mapManager.CurrentMap=graph;
Plugin.IsDefaultMode=true; CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); Check(CustomCoachScope.Current==null,"Default run cannot use a stale custom event"); scope.Dispose(); Plugin.IsDefaultMode=false;
CustomCoachRuntime.Release(map); Check(eventA.Destroyed && eventB.Destroyed && !shared.Destroyed,"Map teardown releases only private event objects");
CustomCoachRuntime.Begin((CoachEvent)eventA,out scope); Check(CustomCoachScope.Current==null,"Released visit no longer owns a pool"); scope.Dispose();
Console.WriteLine($"PASS {checks} source-linked Coach visit checks");
