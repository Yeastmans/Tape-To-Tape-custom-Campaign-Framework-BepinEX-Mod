    public static bool SupportsKind(string effect, string kind)
    {
        var flag = kind switch {
            CustomRewardDefinition.CustomTalents => NativeKind.Talent,
            CustomRewardDefinition.CustomChaosTalents => NativeKind.Chaos,
            CustomRewardDefinition.CustomGoalieTalents => NativeKind.Goalie,
            CustomRewardDefinition.CustomRelics => NativeKind.Relic,
            _ => NativeKind.None
        };
        return NativeKinds.TryGetValue(effect, out var entry) && (entry.Kinds & flag) != 0;
    }
    public static string KindEvidence(string effect) => NativeKinds.TryGetValue(effect, out var entry) ? entry.Evidence : "";
